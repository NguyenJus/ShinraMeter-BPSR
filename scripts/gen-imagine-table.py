#!/usr/bin/env python3
"""Regenerate `crates/app/src/imagines.rs` from the vendored Imagine table.

`crates/app/data/imagine_table.json` is a hand-curated, game-client-derived
table (via BPSR-ZDPS) of the 106 skill ids that are actually equippable
Imagines — see `docs/specs/2026-08-17-issue-33-imagines-spec.md`'s
"Curation" section for how the 125 slot-7/8 `SkillTable.json` rows were
narrowed to 106 by hand-excluding talent-passive stubs, non-player
abilities, and stand-in cosmetics. We keep a verbatim copy for provenance
and compile it into a `match` arm so the lookup is free at runtime and the
binary carries no JSON parser for it — same rationale as
`scripts/gen-name-tables.py` -> `crates/meter/src/tables.rs`.

The icon PNGs referenced by the table are prepared separately by
`scripts/prep-imagine-icons.py` into `crates/app/assets/imagines/`; this
script does not touch them, but it refuses to emit unless every icon
basename the table references resolves to a committed PNG there.

Usage:

    python3 scripts/gen-imagine-table.py          # regenerate from the vendored JSON
    python3 scripts/gen-imagine-table.py --check  # offline: fail if imagines.rs is stale

Refresh only after re-curating `crates/app/data/imagine_table.json`, and run
`cargo fmt -p ShinraMeter-BPSR` after a regeneration. There is no `--refresh`
counterpart to `scripts/gen-name-tables.py`'s: this generator has no networked
upstream: its inputs are the committed curated JSON and the committed PNGs.
`.github/workflows/name-tables.yml` runs `--check` so the generated file cannot
rot silently.
"""

import argparse
import io
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "crates" / "app" / "data" / "imagine_table.json"
ASSETS = ROOT / "crates" / "app" / "assets" / "imagines"
OUT = ROOT / "crates" / "app" / "src" / "imagines.rs"

HEADER = """//! Static Imagine skill-id -> `(name, icon)` table, and the icon basenames
//! it references, loaded from `assets/imagines/` beside the exe at runtime.
//!
//! Generated by `scripts/gen-imagine-table.py` from the hand-curated
//! `crates/app/data/imagine_table.json`, itself derived from the game
//! client via BPSR-ZDPS; see `THIRD_PARTY_NOTICES.md`. Do not edit by hand.
//!
//! // IMAGINE-TAKEDOWN: not one of the five marked sites — this module is
//! // removed via `rm`, not edited in place. See `docs/plans/*imagines-plan.md`
//! // D4. Takedown removes this module, `crates/app/assets/imagines/`,
//! // `crates/app/data/imagine_table.json`, `scripts/prep-imagine-icons.py`,
//! // `scripts/gen-imagine-table.py`, and the five marked sites — now a
//! // directory deletion (`rm -r crates/app/assets/imagines/`) for an
//! // already-distributed copy, not a rebuild.
//!
//! Coverage is a hand-curated allowlist, not every skill id in the game —
//! an id outside the 106 curated Imagines yields `None` from
//! `imagine_of_skill_id`, and callers must treat that as "not an Imagine",
//! never as a lookup failure to surface.
"""


def esc(s: str) -> str:
    """Escape `s` for embedding in a Rust `&'static str` literal.

    Order matters: backslash is escaped first, so the escapes this function
    inserts below are never themselves re-escaped. `\\r`, `\\n`, and `\\t`
    get Rust's short forms; every other control character gets Rust's
    `\\u{...}` form, so a bare CR (or any other control byte) in a future
    re-curation of the vendored JSON can never produce an `imagines.rs` that
    fails to compile with "bare CR not allowed in string" or similar.
    """
    s = s.replace("\\", "\\\\").replace('"', '\\"')
    out = []
    for ch in s:
        if ch == "\r":
            out.append("\\r")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append(f"\\u{{{ord(ch):x}}}")
        else:
            out.append(ch)
    return "".join(out)


def _self_test() -> None:
    """Fast synthetic checks run on every generation. There is no Python
    test harness elsewhere in this repo (no pytest config, no CI job that
    runs Python — see `scripts/` and `.github/workflows/`), so this
    hard-fails inline instead of living in an untested, never-run test
    file.
    """
    assert esc('a\\b"c') == 'a\\\\b\\"c'
    assert esc("line1\rline2") == "line1\\rline2"
    assert esc("line1\nline2") == "line1\\nline2"
    assert esc("a\tb") == "a\\tb"
    assert esc("\x01") == "\\u{1}"
    assert esc("\x7f") == "\\u{7f}"
    # Order: backslash-escaping must not re-escape a literal `\r` that was
    # already produced for a real carriage return.
    assert esc("\\\r") == "\\\\\\r"

    # rustfmt-shape replication: the inline/broken-out decision is made on the
    # joined element list, and the broken-out form carries a trailing comma.
    # Getting either wrong makes `--check` permanently red against a
    # `cargo fmt`-clean file, which is the failure mode this pair exists to
    # avoid.
    assert _fits(["a", "bb"], 5)  # "a, bb" is exactly the budget
    assert not _fits(["a", "bb"], 4)
    assert _fits([], 0)
    assert _broken_out("    ", ["x", "y"]) == "        x,\n        y,\n"
    assert _broken_out("", []) == ""

    # canonical_name_by_icon: happy path — the 39xx canonical rows win,
    # non-canonical rows (e.g. a 102xxx variant sharing the same icon) are
    # ignored when building the map.
    canon = canonical_name_by_icon(
        [
            {"id": 3901, "name": "A", "icon": "icon_a"},
            {"id": 3902, "name": "B", "icon": "icon_b"},
            {"id": 102640, "name": "not the canonical name", "icon": "icon_a"},
        ]
    )
    assert canon == {"icon_a": "A", "icon_b": "B"}

    # canonical_name_by_icon: two canonical (39xx) rows disagreeing on the
    # name for the same icon breaks the bijection this whole scheme relies
    # on and must hard-fail rather than silently pick one.
    try:
        canonical_name_by_icon(
            [
                {"id": 3901, "name": "A", "icon": "icon_a"},
                {"id": 3902, "name": "A-prime", "icon": "icon_a"},
            ]
        )
        raise AssertionError("expected SystemExit for a non-bijective canonical range")
    except SystemExit:
        pass

    # resolve_canonical_names: a variant resolves to the canonical name, not
    # its own (possibly divergent) raw name.
    resolved = resolve_canonical_names(
        [
            {"id": 3901, "name": "A", "icon": "icon_a"},
            {"id": 102640, "name": "variant's own wrong name", "icon": "icon_a"},
        ],
        {"icon_a": "A"},
    )
    assert resolved == {3901: "A", 102640: "A"}

    # resolve_canonical_names: an "orphan" icon with no canonical entry must
    # hard-fail rather than fall back to the variant's own name — that
    # fallback is exactly the bug this resolution step exists to fix.
    try:
        resolve_canonical_names([{"id": 999, "name": "Orphan", "icon": "icon_zzz"}], {})
        raise AssertionError("expected SystemExit for an orphan icon")
    except SystemExit:
        pass


def canonical_name_by_icon(entries: list[dict]) -> dict[str, str]:
    """Icon basename -> canonical display name, built only from ids in the
    3900-3999 "canonical" range (spec's "Many-to-one is expected — identity
    is the icon basename"). A canonical icon must name exactly one Imagine —
    if two canonical rows disagree, "the canonical name" is not well-defined
    and the curated data is broken, so this hard-fails rather than picking a
    winner.
    """
    canonical: dict[str, str] = {}
    for e in entries:
        if 3900 <= e["id"] < 4000:
            icon, name = e["icon"], e["name"]
            if icon in canonical and canonical[icon] != name:
                raise SystemExit(
                    f"refusing to emit: canonical icon {icon!r} names both "
                    f"{canonical[icon]!r} and {name!r} among ids 3900-3999 - "
                    "the icon<->name bijection in the canonical range is broken"
                )
            canonical[icon] = name
    return canonical


def resolve_canonical_names(entries: list[dict], canonical: dict[str, str]) -> dict[int, str]:
    """id -> canonical display name for every entry, resolving a variant id
    to its canonical (39xx) name via icon identity — the fix for the bug
    caught in review: deduping by an id's own raw name let one equipped
    Imagine occupy both of a player's slots (e.g. `3905` and `102651` both
    render "the Boar Imagine" but had different raw names). Every entry's
    icon must already be in `canonical` (the spec's "zero orphans" claim);
    an orphan hard-fails instead of silently falling back to the variant's
    own name, which would reintroduce that bug.
    """
    resolved: dict[int, str] = {}
    orphans: list[int] = []
    for e in entries:
        name = canonical.get(e["icon"])
        if name is None:
            orphans.append(e["id"])
        else:
            resolved[e["id"]] = name
    if orphans:
        raise SystemExit(
            "refusing to emit: these ids reference an icon with no canonical "
            f"(3900-3999) name - orphan icons: {sorted(orphans)}"
        )
    return resolved


# rustfmt's own wrapping rules, replicated here so `render()` emits byte-for-byte
# what `cargo fmt` would produce. Without this the generated file and the
# committed file could only ever agree after a `cargo fmt` pass, and `--check`
# would need a Rust toolchain it deliberately does not have — the same reason
# `scripts/gen-name-tables.py` reproduces rustfmt's array packing in
# `_BOSS_IDS_LINE_WIDTH`. Both numbers are rustfmt defaults (`fn_call_width` is
# the budget a tuple literal's element list gets before rustfmt breaks it one
# element per line; `struct_lit_width` is the same budget for a struct
# literal's fields), and this repo ships no `rustfmt.toml` overriding them.
_FN_CALL_WIDTH = 60
_STRUCT_LIT_WIDTH = 18


def _fits(items: list[str], budget: int) -> bool:
    """Whether rustfmt would keep `items` inline inside their delimiters."""
    return len(", ".join(items)) <= budget


def _broken_out(indent: str, items: list[str]) -> str:
    """rustfmt's broken-out form: one element per line, each trailing-comma'd."""
    return "".join(f"{indent}    {item},\n" for item in items)


def emit_lookup(out: io.StringIO, entries: list[dict], canonical_name_of_id: dict[int, str]) -> None:
    out.write(
        "\n/// One equippable Imagine's display data.\n"
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n"
        "pub struct Imagine {\n"
        "    pub name: &'static str,\n"
        "    pub icon: &'static str,\n"
        "}\n"
    )
    out.write(
        "\n/// Look up the Imagine a skill id belongs to, if `id` is one of the 106\n"
        "/// curated ids. An id outside that set (including every excluded id in\n"
        "/// `crates/app/data/imagine_table.json`'s `_excluded`) yields `None` —\n"
        "/// that is the mechanism by which non-Imagine skill ids are dropped\n"
        "/// rather than mis-rendered as a slot.\n"
        "///\n"
        "/// `name` is always the *canonical* (39xx) name for the id's icon, not\n"
        "/// necessarily the id's own raw `SkillTable.json` name: identity is the\n"
        "/// icon basename, not the name (spec's \"Many-to-one is expected\"). A\n"
        "/// variant id whose own name disagrees with its canonical row (e.g.\n"
        "/// `102651`'s raw name is \"Boar Knight\", but it shares an icon with\n"
        "/// the canonical `3905` \"Stunt! Boarrier Rush\" and resolves to that\n"
        "/// name here) must resolve to the canonical name — deduping by an id's\n"
        "/// own raw name would let one equipped Imagine occupy both of a\n"
        "/// player's two slots.\n"
        "pub fn imagine_of_skill_id(id: i32) -> Option<Imagine> {\n"
        "    Some(match id {\n"
    )
    for e in sorted(entries, key=lambda e: e["id"]):
        fields = [
            'name: "%s"' % esc(canonical_name_of_id[e["id"]]),
            'icon: "%s"' % esc(e["icon"]),
        ]
        head = "        %d => Imagine" % e["id"]
        if _fits(fields, _STRUCT_LIT_WIDTH):
            out.write("%s { %s },\n" % (head, ", ".join(fields)))
        else:
            out.write("%s {\n%s        },\n" % (head, _broken_out("        ", fields)))
    out.write("        _ => return None,\n    })\n}\n")


def emit_icon_files(out: io.StringIO, icons: list[str]) -> None:
    out.write(
        "\n/// Every icon basename referenced by `imagine_of_skill_id`. These are\n"
        "/// not embedded: the app reads `<assets>/imagines/<basename>.png` off\n"
        "/// disk at runtime (see `crate::assets` and `icons.rs`'s `ImagineIcons`).\n"
        "/// Non-exhaustive `&[&str]` form (mirrors `TOOLBAR_ICON_BYTES` in\n"
        "/// `icons.rs`), not an exhaustive macro like `class_icons!` — the key\n"
        "/// set is an open-ended game-data id, not a small fixed enum, so there\n"
        "/// is no \"missing variant\" compile-time guarantee to buy.\n"
        "pub const IMAGINE_ICON_FILES: &[&str] = &[\n"
    )
    for icon in sorted(icons):
        out.write('    "%s",\n' % esc(icon))
    out.write("];\n")


