def emit_all_entries(out: io.StringIO, entries: list[dict]) -> None:
    out.write(FOOTER_HEADER)
    for e in sorted(entries, key=lambda e: e["id"]):
        items = ["%d" % e["id"], '"%s"' % esc(e["name"]), '"%s"' % esc(e["icon"])]
        if _fits(items, _FN_CALL_WIDTH):
            out.write("    (%s),\n" % ", ".join(items))
        else:
            out.write("    (\n%s    ),\n" % _broken_out("    ", items))
    out.write("];\n")
    out.write(FOOTER_TAIL)


def render() -> str:
    """Build the full text of `imagines.rs` from the vendored JSON and assets.

    Every pre-emit invariant lives here rather than on the write path, so
    `--check` enforces exactly the same refusals a regeneration would.
    """
    table = json.loads(DATA.read_text(encoding="utf-8"))
    entries = table["imagines"]
    counts = table["_counts"]

    assert len(entries) == counts["imagines"], (
        f"imagine_table.json: {len(entries)} entries in 'imagines' but "
        f"_counts.imagines says {counts['imagines']}"
    )
    distinct_names = {e["name"] for e in entries}
    distinct_icons = {e["icon"] for e in entries}
    assert len(distinct_names) == counts["distinct_names"], (
        f"imagine_table.json: {len(distinct_names)} distinct names but "
        f"_counts.distinct_names says {counts['distinct_names']}"
    )
    assert len(distinct_icons) == counts["distinct_icons"], (
        f"imagine_table.json: {len(distinct_icons)} distinct icons but "
        f"_counts.distinct_icons says {counts['distinct_icons']}"
    )

    missing = sorted(
        icon for icon in distinct_icons if not (ASSETS / f"{icon}.png").is_file()
    )
    if missing:
        raise SystemExit(
            "refusing to emit: the following icon basenames are referenced by "
            f"imagine_table.json but have no PNG under {ASSETS}:\n  "
            + "\n  ".join(missing)
        )

    # Identity-is-the-icon invariants (design correction after review caught
    # the original name-dedup bug): these are what make "resolve every id to
    # its canonical (39xx) name" a safe, well-defined operation. Data-
    # dependent, so — like the asset-existence check above — they run here
    # rather than in `_self_test()`, which only exercises the pure helpers
    # against synthetic data.
    canonical_range = [e for e in entries if 3900 <= e["id"] < 4000]
    canonical_range_icons = {e["icon"] for e in canonical_range}
    canonical_range_names = {e["name"] for e in canonical_range}
    if len(canonical_range_icons) != 81 or len(canonical_range_names) != 81:
        raise SystemExit(
            "refusing to emit: expected exactly 81 distinct icons and 81 "
            "distinct names among ids 3900-3999 (the canonical range), got "
            f"{len(canonical_range_icons)} icons / {len(canonical_range_names)} names"
        )
    canonical_by_icon = canonical_name_by_icon(entries)  # raises if non-bijective
    if len(set(canonical_by_icon.values())) != len(canonical_by_icon):
        raise SystemExit(
            "refusing to emit: two different canonical icons share the same "
            "canonical name - the icon<->name bijection is broken"
        )
    canonical_name_of_id = resolve_canonical_names(entries, canonical_by_icon)  # raises on orphans
    assert set(canonical_name_of_id) == {e["id"] for e in entries}, (
        "canonical-name resolution must be total over every curated id"
    )

    out = io.StringIO()
    out.write(HEADER)
    emit_lookup(out, entries, canonical_name_of_id)
    emit_icon_files(out, sorted(distinct_icons))
    emit_all_entries(out, entries)
    print(
        f"{len(entries)} imagines, {len(distinct_names)} distinct raw names, "
        f"{len(distinct_icons)} distinct icons, {len(canonical_by_icon)} canonical names",
        file=sys.stderr,
    )
    return out.getvalue()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; exit 1 if the generated file is out of date",
    )
    args = parser.parse_args()

    _self_test()

    rendered = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else None
        if current != rendered:
            was = "missing" if current is None else f"{len(current)} chars"
            print(f"DRIFT: {OUT} is out of date ({was} on disk, {len(rendered)} chars generated)")
            print("\nrun `python3 scripts/gen-imagine-table.py` and commit the result")
            sys.exit(1)
        print("imagine table is up to date")
        return

    OUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
